/** 表示言語に対応する <html lang> の値 */
export function htmlLangFor(lng: string | undefined): 'ja' | 'en' {
  return lng?.startsWith('ja') ? 'ja' : 'en';
}

const initialLanguage = htmlLangFor(navigator.language);

i18n.use(initReactI18next).init({
  resources,
  lng: initialLanguage,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false, // React は自動エスケープ
  },
});

// <html lang> を表示言語に合わせる。固定の "en" のままだと、日本語の画面をブラウザが
// 「英語のページ」と判断し、自動翻訳で「SENN」が「セン」になるなど表記が変わってしまう。
function syncHtmlLang(lng: string | undefined): void {
  if (typeof document !== 'undefined') {
    document.documentElement.lang = htmlLangFor(lng);
  }
}
syncHtmlLang(initialLanguage);
i18n.on('languageChanged', syncHtmlLang);

export default i18n;
